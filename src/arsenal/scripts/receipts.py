def get_receipt(original_path_or_canonical_id: str) -> dict[str, Any] | None:
    """Find a script migration receipt by original path or canonical ID."""
    for r in SCRIPT_RECEIPTS:
        if r["original_path"] == original_path_or_canonical_id or r["canonical_id"] == original_path_or_canonical_id:
            return r
    return None


def list_receipts(status_filter: str | None = None) -> list[dict[str, Any]]:
    """List all script receipts, optionally filtered by status."""
    if status_filter:
        return [r for r in SCRIPT_RECEIPTS if r["status"] == status_filter]
    return list(SCRIPT_RECEIPTS)
